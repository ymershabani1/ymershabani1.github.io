window.KAKS_PDF = "/assets/catalogs/katalog-produkti.pdf";
window.KAKS = {
  getCategory: function (catId) {
    return window.KAKS_CATALOG[catId] || null;
  },
  getProduct: function (catId, index) {
    var cat = window.KAKS.getCategory(catId);
    if (!cat || !cat.products || !cat.products.length) return null;
    var i = ((Number(index) % cat.products.length) + cat.products.length) % cat.products.length;
    return { category: cat, product: cat.products[i], index: i, catId: catId };
  },
  escapeHtml: function (str) {
    return String(str)
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;");
  },
  pdfName: function (name) {
    return String(name).toLowerCase().replace(/[^a-z0-9]+/gi, "-") + ".pdf";
  }
};
